#include "libft.h"

int ft_atoi(const char *nptr)
{
    int     i;
    long long       rst;
    int     sign;

    i = 0;
    rst = 0;
    sign = 1;
    while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
        i++;
    if (nptr[i] == '+' || nptr[i] == '-')
    {
        if (nptr[i] == '-')
            sign *= -1;
        i++;
    }
    while (nptr[i] >= '0' && nptr[i] <= '9')
    {
        rst = (rst * 10) + (nptr[i] - '0');
        i++;
    }
    return (rst * sign);
}